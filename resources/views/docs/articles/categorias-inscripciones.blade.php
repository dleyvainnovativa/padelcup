<p class="docs-lead">Las categorías son el corazón de tu torneo: cada una tiene su propio formato,
precio e inscripciones. Aquí verás cómo crearlas y cómo llegan las parejas.</p>

<h2>Crear una categoría</h2>
<ol class="docs-steps">
    <li>
        <strong>Entra a tu torneo</strong> y pulsa <em>«Nueva categoría»</em>.
    </li>
    <li>
        <strong>Ponle nombre</strong> (por ejemplo, «4ta Fuerza Varonil» o «Mixto B»).
    </li>
    <li>
        <strong>Elige el formato.</strong>
        Define si es de grupos, eliminación directa, o una combinación. También el formato de juego (parejas o singles) y cuántas parejas avanzan de cada grupo.
    </li>
    <li>
        <strong>Configura precio e inscripciones.</strong>
        Indica el costo por pareja y las fechas en que las inscripciones estarán abiertas para esa categoría.
    </li>
    <li>
        <strong>Guarda.</strong>
        Repite para cada categoría que tenga tu torneo.
    </li>
</ol>

<h2>Cómo llegan las parejas</h2>
<p>Hay tres formas de tener parejas en una categoría:</p>

<ol class="docs-steps">
    <li>
        <strong>Inscripción en línea.</strong>
        Si compartes la página pública del torneo, los jugadores se inscriben ellos mismos y pagan en línea. Aparecen automáticamente en la categoría.
    </li>
    <li>
        <strong>Alta manual.</strong>
        Desde el panel puedes agregar parejas a mano, útil para inscripciones que recibiste por WhatsApp o en persona.
    </li>
    <li>
        <strong>Importar desde Excel.</strong>
        Si ya tienes tu lista en una hoja de cálculo, usa la opción <em>Importar</em> para subirlas todas de golpe. Voleo detecta duplicados y te avisa antes de confirmar.
    </li>
</ol>

<div class="docs-note">
    <i class="fa-solid fa-lightbulb"></i>
    <span>Puedes combinar los tres métodos en la misma categoría. Por ejemplo, abrir inscripción en línea y además agregar a mano las parejas que pagaron en efectivo.</span>
</div>

<h2>Revisar las parejas inscritas</h2>
<p>Dentro de cada categoría verás la lista de parejas con su estado de pago. Desde ahí puedes editar, mover o dar de baja una pareja antes de generar los grupos.</p>
