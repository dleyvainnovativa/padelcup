<p class="docs-lead">Cada torneo tiene su propia página pública: calendario, resultados y
standings al instante. Es también donde los jugadores se inscriben y pagan.</p>

<h2>Compartir tu torneo</h2>
<ol class="docs-steps">
    <li><strong>Entra a tu torneo</strong> y pulsa <em>«Compartir / QR»</em>.</li>
    <li><strong>Copia el enlace</strong> o descarga el código QR para imprimirlo en tu club.</li>
    <li><strong>Difúndelo</strong> por WhatsApp, redes o en la cancha. Cualquiera con el enlace puede seguir el torneo.</li>
</ol>

<h2>Cobros en línea</h2>
<p>Si conectas tu cuenta de pagos, los jugadores pueden inscribirse y pagar directamente desde la página pública. Verás el detalle de cada pago en tu panel.</p>

