<p class="docs-lead">Capturar resultados es rápido y los standings se actualizan solos.
Tus jugadores ven todo en tiempo real desde la página pública.</p>

<h2>Registrar un marcador</h2>
<ol class="docs-steps">
    <li><strong>Abre el partido</strong> desde la categoría o el calendario.</li>
    <li><strong>Ingresa los sets</strong> de cada pareja.</li>
    <li><strong>Confirma.</strong> El ganador avanza automáticamente en el cuadro y la tabla de posiciones se recalcula.</li>
</ol>

<h2>Standings en vivo</h2>
<p>Conforme capturas resultados, los standings de cada grupo se ordenan según los criterios de desempate del torneo. No tienes que calcular nada a mano.</p>

<div class="docs-note">
    <i class="fa-solid fa-lightbulb"></i>
    <span>Si te equivocas, puedes corregir un marcador. Voleo recalcula todo lo que dependa de ese partido.</span>
</div>

