<p class="docs-lead">Cuando tus parejas están inscritas, Voleo arma la fase de grupos y el cuadro
de eliminación automáticamente. Aquí verás cómo generarlos y ajustarlos.</p>

<h2>Generar la estructura</h2>
<ol class="docs-steps">
    <li><strong>Entra a la categoría</strong> que quieras armar.</li>
    <li><strong>Pulsa «Generar».</strong> Voleo reparte las parejas en grupos según el tamaño que configuraste y crea el cuadro de eliminación con la siembra correspondiente.</li>
    <li><strong>Revisa el resultado.</strong> Verás los grupos con sus parejas y el bracket ya conectado.</li>
</ol>

<div class="docs-note">
    <i class="fa-solid fa-lightbulb"></i>
    <span>Puedes regenerar mientras no haya resultados capturados. Una vez que empieza el juego, los cambios son más limitados para no romper el cuadro.</span>
</div>

<h2>Ajustar manualmente</h2>
<p>¿Necesitas mover una pareja de grupo o cambiar una siembra? Puedes hacerlo arrastrando y soltando antes de que inicie el torneo.</p>

