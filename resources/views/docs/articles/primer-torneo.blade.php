<p class="docs-lead">Crear un torneo en Voleo toma solo unos minutos. Aquí verás cómo darlo de alta,
definir sus fechas y dejarlo listo para agregar categorías.</p>

<h2>Antes de empezar</h2>
<p>Necesitas una cuenta de organizador. Si aún no tienes una, entra a <a href="{{ route('register') }}">crear cuenta</a> y regístrate; es gratis y solo toma un momento.</p>

<h2>Paso a paso</h2>
<ol class="docs-steps">
    <li>
        <strong>Entra a tu panel.</strong>
        Inicia sesión y ve a la sección <em>Torneos</em>. Verás la lista de tus torneos (vacía si es tu primera vez).
    </li>
    <li>
        <strong>Pulsa «Nuevo torneo».</strong>
        El botón está arriba a la derecha. Se abrirá el formulario de creación.
    </li>
    <li>
        <strong>Completa la información básica.</strong>
        Ponle un nombre claro (por ejemplo, «Copa Primavera 2026»), una descripción corta y, si quieres, un logo y una imagen de portada. Estos aparecerán en la página pública del torneo.
    </li>
    <li>
        <strong>Define fechas y horarios de juego.</strong>
        Indica el día de inicio y fin, y el horario en que se jugará cada día. Voleo usa estos datos más adelante para armar el calendario de partidos.
    </li>
    <li>
        <strong>Guarda.</strong>
        Al guardar, tu torneo queda creado en modo <em>borrador</em>. Nadie lo verá hasta que tú decidas publicarlo.
    </li>
</ol>

<div class="docs-note">
    <i class="fa-solid fa-lightbulb"></i>
    <span>Puedes editar todos estos datos después. En esta etapa lo importante es dejar el torneo creado para empezar a agregar categorías.</span>
</div>

<h2>¿Y ahora qué?</h2>
<p>Con el torneo creado, el siguiente paso es agregar categorías y abrir inscripciones. Lo vemos en la siguiente guía.</p>
